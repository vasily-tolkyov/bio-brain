export const diverging = (v) => {
  const x = Math.max(-1, Math.min(1, v));
  return x >= 0 ? [Math.round(255 - 222 * x), Math.round(255 - 142 * x), Math.round(255 - 74 * x)] : [Math.round(255 + 40 * x), Math.round(255 + 200 * x), Math.round(255 + 200 * x)];
};
