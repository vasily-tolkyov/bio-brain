export class Canvas {
  constructor(w, h, bg = [255, 255, 255]) {
    this.w = w; this.h = h;
    this.px = Buffer.alloc(w * h * 3);
    for (let i = 0; i < w * h; i++) this.px.set(bg, i * 3);
  }
  set(x, y, c) { x |= 0; y |= 0; if (x < 0 || y < 0 || x >= this.w || y >= this.h) return; this.px.set(c, (y * this.w + x) * 3); }
  rect(x, y, w, h, c) { for (let j = Math.max(0, y | 0); j < Math.min(this.h, (y + h) | 0); j++) for (let i = Math.max(0, x | 0); i < Math.min(this.w, (x + w) | 0); i++) this.px.set(c, (j * this.w + i) * 3); }
  line(x0, y0, x1, y1, c, width = 1) {
    const n = Math.max(1, Math.ceil(Math.hypot(x1 - x0, y1 - y0)));
    for (let k = 0; k <= n; k++) { const x = x0 + ((x1 - x0) * k) / n, y = y0 + ((y1 - y0) * k) / n; this.rect(x - width / 2, y - width / 2, width, width, c); }
  }
  /** 5×7 点阵字，scale 倍放大；不认识的字符画成空格 */
  text(x, y, s, c = [0, 0, 0], scale = 2) {
    let cx = x;
    for (const ch of String(s).toUpperCase()) {
      const g = FONT[ch] ?? FONT[' '];
      for (let r = 0; r < 7; r++) for (let q = 0; q < 5; q++) if (g[r][q] === '1') this.rect(cx + q * scale, y + r * scale, scale, scale, c);
      cx += 6 * scale;
    }
    return cx;
  }
  save(file) {
    const raw = Buffer.alloc((this.w * 3 + 1) * this.h);
    for (let y = 0; y < this.h; y++) { raw[y * (this.w * 3 + 1)] = 0; this.px.copy(raw, y * (this.w * 3 + 1) + 1, y * this.w * 3, (y + 1) * this.w * 3); }
    const ihdr = Buffer.alloc(13);
    ihdr.writeUInt32BE(this.w, 0); ihdr.writeUInt32BE(this.h, 4); ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
    fs.writeFileSync(file, Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]));
  }
}

/** 0–1 → 白—蓝—深蓝—黑的连续色（矩阵热图用） */
export const heat = (v) => {
  const x = Math.min(1, Math.max(0, v));
  const stops = [[255, 255, 255], [158, 202, 225], [33, 113, 181], [8, 48, 107], [0, 0, 0]];
  const s = x * (stops.length - 1), i = Math.min(stops.length - 2, Math.floor(s)), f = s - i;
  return stops[i].map((a, k) => Math.round(a + (stops[i + 1][k] - a) * f));
};
